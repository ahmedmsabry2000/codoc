"""Write engine and Vale files from ProjectConfig."""

import os
import tempfile
from dataclasses import dataclass
from pathlib import Path

import yaml

from codoc.config import ConfigError, ProjectConfig, load_project_config
from codoc.discover import DiscoverError, git_root
from codoc.engine.engulf import EngulfError, engulf_project
from codoc.engine.vocab import grow_learned, merge_accept_terms, read_learned

_GENERATED_DIR = Path(".codoc") / "generated"
# Zensical treats the config file's directory as the project root and rejects
# docs_dir/site_dir that use '..'. Absolute site_dir also fails. So the shim
# must sit at the git root — but it is not named mkdocs.yml and is not SoT.
ENGINE_SHIM = Path(".codoc-engine.yml")
_VALE_INI = _GENERATED_DIR / ".vale.ini"
# Vale 3 looks under StylesPath/config/vocabularies/<Vocab>/.
_VOCAB_DIR = _GENERATED_DIR / "styles" / "config" / "vocabularies" / "Codoc"
_ACCEPT = _VOCAB_DIR / "accept.txt"
_REJECT = _VOCAB_DIR / "reject.txt"

_HEADER = (
    "# Generated by codoc from codoc.yaml. Do not edit.\n"
    "# Source of truth: engine settings in codoc.yaml.\n"
)


class CodegenError(Exception):
    """Generated config files could not be written."""


@dataclass(frozen=True, slots=True)
class GeneratedPaths:
    root: Path
    engine: Path
    vale_ini: Path | None
    vocab_accept: Path | None
    written: tuple[Path, ...]
    notes: tuple[str, ...] = ()
    learned_added: tuple[str, ...] = ()


def ensure_generated(
    start: Path | None = None,
    *,
    learn: bool = True,
) -> GeneratedPaths:
    """Load codoc.yaml at the git root and refresh generated engine/Vale files."""
    if start is None:
        start = Path.cwd()
    try:
        root = git_root(start)
    except DiscoverError as err:
        raise CodegenError(str(err)) from err
    project_path = root / "codoc.yaml"
    if not project_path.is_file():
        raise CodegenError(f"codoc.yaml not found at {project_path}")
    try:
        config = load_project_config(project_path)
    except ConfigError as err:
        raise CodegenError(str(err)) from err
    try:
        outcome = engulf_project(root, config, fill_defaults_only=True, project_path=project_path)
    except EngulfError as err:
        raise CodegenError(str(err)) from err
    notes = (outcome.note,) if outcome.note else ()
    return write_generated(root, outcome.config, notes=notes, learn=learn)


def write_generated(
    root: Path,
    config: ProjectConfig,
    *,
    notes: tuple[str, ...] = (),
    learn: bool = True,
) -> GeneratedPaths:
    """Materialize the engine shim and Vale files from ProjectConfig."""
    name = config.engine.name.lower()
    if name not in {"zensical", "mkdocs"}:
        raise CodegenError(f"unsupported engine {config.engine.name!r}")

    written: list[Path] = []
    engine_rel = ENGINE_SHIM
    engine_text = _render_engine(config)
    _atomic_write(root / engine_rel, engine_text)
    written.append(engine_rel)

    vale_ini: Path | None = None
    vocab_accept: Path | None = None
    learned_added: tuple[str, ...] = ()
    extra_notes = list(notes)
    if config.vale.enabled:
        if learn:
            growth = grow_learned(
                root,
                Path(config.engine.docs_dir),
                seed=config.terms,
            )
            learned_added = growth.added
            written.append(growth.learned_path)
            if growth.added:
                extra_notes.append(f"learned {len(growth.added)} new term(s)")
        learned = read_learned(root)
        accept_terms = merge_accept_terms(config.terms, learned)
        vale_ini = _VALE_INI
        vocab_accept = _ACCEPT
        _atomic_write(root / vale_ini, _render_vale_ini())
        written.append(vale_ini)
        _atomic_write(root / vocab_accept, _render_accept(accept_terms))
        written.append(vocab_accept)
        reject = _REJECT
        if not (root / reject).exists():
            _atomic_write(root / reject, "")
            written.append(reject)

    ordered = tuple(sorted(set(written), key=lambda path: path.as_posix()))
    return GeneratedPaths(
        root=root,
        engine=engine_rel,
        vale_ini=vale_ini,
        vocab_accept=vocab_accept,
        written=ordered,
        notes=tuple(extra_notes),
        learned_added=learned_added,
    )


def _render_engine(config: ProjectConfig) -> str:
    body: dict = {
        "site_name": config.engine.site_name,
        "docs_dir": Path(config.engine.docs_dir).as_posix(),
        "site_dir": Path(config.engine.site_dir).as_posix(),
    }
    if config.engine.theme is not None:
        body["theme"] = config.engine.theme
    if config.engine.nav is not None:
        body["nav"] = config.engine.nav
    dumped = yaml.safe_dump(body, sort_keys=False, default_flow_style=False)
    assert isinstance(dumped, str)
    return f"{_HEADER}{dumped}"


def _render_vale_ini() -> str:
    # Vocab accept lists feed Spelling. Terms capitalization is too noisy for
    # mixed-case docs headings, so leave it off for the Mac pilot.
    return (
        f"{_HEADER}"
        "StylesPath = styles\n"
        "MinAlertLevel = suggestion\n"
        "Vocab = Codoc\n"
        "\n"
        "[*.md]\n"
        "BasedOnStyles = Vale\n"
        "Vale.Terms = NO\n"
    )


def _render_accept(terms: tuple[str, ...]) -> str:
    if not terms:
        return ""
    return "".join(f"{term}\n" for term in terms)


def _atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    tmp = Path(tmp_name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(text)
        os.replace(tmp, path)
    except Exception:
        tmp.unlink(missing_ok=True)
        raise
