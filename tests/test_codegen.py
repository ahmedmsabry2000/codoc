import io
import os
import subprocess
import tempfile
import unittest
from collections.abc import Iterator
from contextlib import contextmanager, redirect_stderr, redirect_stdout
from pathlib import Path

import codoc.cli as cli
from codoc.codegen import CodegenError, ensure_generated, write_generated
from codoc.config import load_project_config
from codoc.init_cmd import run_init


@contextmanager
def _git_repo() -> Iterator[Path]:
    with tempfile.TemporaryDirectory() as raw:
        root = Path(raw)
        subprocess.run(
            ["git", "init", "-q"],
            cwd=root,
            check=True,
            capture_output=True,
            text=True,
        )
        yield root


def _run_in(path: Path, argv: list[str]) -> tuple[str, str, int | None]:
    previous = os.getcwd()
    os.chdir(path)
    stdout = io.StringIO()
    stderr = io.StringIO()
    code: int | None = None
    try:
        with redirect_stdout(stdout), redirect_stderr(stderr):
            try:
                cli.main(argv)
            except SystemExit as caught:
                status = caught.code
                code = status if isinstance(status, int) else None
        return stdout.getvalue(), stderr.getvalue(), code
    finally:
        os.chdir(previous)


class CodegenTests(unittest.TestCase):
    def test_round_trip_from_codoc_yaml(self) -> None:
        with _git_repo() as repo:
            (repo / "codoc.yaml").write_text(
                "\n".join(
                    [
                        "engine:",
                        "  name: zensical",
                        "  docs_dir: docs",
                        "  site_dir: site",
                        "vale:",
                        "  enabled: true",
                        "terms:",
                        "  - Codoc",
                        "  - Zensical",
                        "",
                    ]
                ),
                encoding="utf-8",
            )
            result = ensure_generated(repo)
            engine = (repo / result.engine).read_text(encoding="utf-8")
            self.assertIn("Generated by codoc", engine)
            self.assertIn("docs_dir: docs", engine)
            self.assertIn("site_dir: site", engine)
            self.assertEqual(result.engine.as_posix(), "mkdocs.yml")
            self.assertIsNotNone(result.vale_ini)
            vale = (repo / result.vale_ini).read_text(encoding="utf-8")
            self.assertIn("Vocab = Codoc", vale)
            self.assertIn("StylesPath = styles", vale)
            accept = (repo / result.vocab_accept).read_text(encoding="utf-8")
            self.assertEqual(accept, "Codoc\nZensical\n")
            self.assertTrue((repo / ".codoc" / "generated" / "styles" / "Vocab" / "Codoc" / "reject.txt").is_file())

    def test_vale_disabled_skips_vale_files(self) -> None:
        with _git_repo() as repo:
            (repo / "codoc.yaml").write_text(
                "vale:\n  enabled: false\n",
                encoding="utf-8",
            )
            config = load_project_config(repo / "codoc.yaml")
            self.assertFalse(config.vale.enabled)
            result = write_generated(repo, config)
            self.assertIsNone(result.vale_ini)
            self.assertTrue((repo / result.engine).is_file())
            self.assertFalse((repo / ".codoc" / "generated" / ".vale.ini").exists())

    def test_unsupported_engine(self) -> None:
        with _git_repo() as repo:
            (repo / "codoc.yaml").write_text(
                "engine:\n  name: hugo\n",
                encoding="utf-8",
            )
            with self.assertRaises(CodegenError) as caught:
                ensure_generated(repo)
            self.assertIn("unsupported engine", str(caught.exception))

    def test_lint_writes_generated_and_exits_zero(self) -> None:
        with _git_repo() as repo:
            run_init(repo)
            out, err, code = _run_in(repo, ["lint"])
        self.assertEqual(code, 0)
        self.assertIn("mkdocs.yml", out)
        self.assertIn(".codoc/generated/.vale.ini", out)
        self.assertIn("codoc lint: vale not invoked", err)

    def test_missing_codoc_yaml(self) -> None:
        with _git_repo() as repo:
            with self.assertRaises(CodegenError):
                ensure_generated(repo)


if __name__ == "__main__":
    unittest.main()
