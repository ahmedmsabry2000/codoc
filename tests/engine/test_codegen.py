import subprocess
from collections.abc import Iterator
from contextlib import contextmanager
from pathlib import Path

import pytest

from codoc.config import load_project_config
from codoc.engine.codegen import CodegenError, ensure_generated, write_generated
from tests.support.tmpdir import temporary_directory


@contextmanager
def _git_repo() -> Iterator[Path]:
    with temporary_directory() as root:
        subprocess.run(
            ["git", "init", "-q"],
            cwd=root,
            check=True,
            capture_output=True,
            text=True,
        )
        yield root


class CodegenTests:
    def test_round_trip_from_codoc_yaml(self) -> None:
        with _git_repo() as repo:
            (repo / "codoc.yaml").write_text(
                "\n".join(
                    [
                        "engine:",
                        "  name: zensical",
                        "  docs_dir: docs",
                        "  site_dir: site",
                        "vale:",
                        "  enabled: true",
                        "terms:",
                        "  - Codoc",
                        "  - Zensical",
                        "",
                    ]
                ),
                encoding="utf-8",
            )
            result = ensure_generated(repo)
            engine = (repo / result.engine).read_text(encoding="utf-8")
            assert "Generated by codoc" in engine
            assert "docs_dir: docs" in engine
            assert "site_dir: site" in engine
            assert result.engine.as_posix() == ".codoc-engine.yml"
            assert (repo / ".codoc-engine.yml").is_file()
            assert not (repo / "mkdocs.yml").exists()
            assert result.vale_ini is not None
            vale = (repo / result.vale_ini).read_text(encoding="utf-8")
            assert "Vocab = Codoc" in vale
            assert "StylesPath = styles" in vale
            accept = (repo / result.vocab_accept).read_text(encoding="utf-8")
            assert accept == "Codoc\nZensical\n"
            assert (
                repo / ".codoc" / "generated" / "styles" / "Vocab" / "Codoc" / "reject.txt"
            ).is_file()

    def test_vale_disabled_skips_vale_files(self) -> None:
        with _git_repo() as repo:
            (repo / "codoc.yaml").write_text(
                "vale:\n  enabled: false\n",
                encoding="utf-8",
            )
            config = load_project_config(repo / "codoc.yaml")
            assert not config.vale.enabled
            result = write_generated(repo, config)
            assert result.vale_ini is None
            assert (repo / result.engine).is_file()
            assert not (repo / ".codoc" / "generated" / ".vale.ini").exists()

    def test_unsupported_engine(self) -> None:
        with _git_repo() as repo:
            (repo / "codoc.yaml").write_text(
                "engine:\n  name: hugo\n",
                encoding="utf-8",
            )
            with pytest.raises(CodegenError) as caught:
                ensure_generated(repo)
            assert "unsupported engine" in str(caught.value)

    def test_missing_codoc_yaml(self) -> None:
        with _git_repo() as repo, pytest.raises(CodegenError):
            ensure_generated(repo)
