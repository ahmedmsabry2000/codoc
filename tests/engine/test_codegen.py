from pathlib import Path

import pytest

from codoc.config import load_project_config
from codoc.engine.codegen import CodegenError, ensure_generated, write_generated


class CodegenTests:
    def test_round_trip_from_codoc_yaml(self, git_repo: Path) -> None:
        (git_repo / "codoc.yaml").write_text(
            "\n".join(
                [
                    "engine:",
                    "  name: zensical",
                    "  docs_dir: docs",
                    "  site_dir: site",
                    "vale:",
                    "  enabled: true",
                    "terms:",
                    "  - Codoc",
                    "  - Zensical",
                    "",
                ]
            ),
            encoding="utf-8",
        )
        result = ensure_generated(git_repo)
        engine = (git_repo / result.engine).read_text(encoding="utf-8")
        assert "Generated by codoc" in engine
        assert "docs_dir: docs" in engine
        assert "site_dir: site" in engine
        assert result.engine.as_posix() == ".codoc-engine.yml"
        assert (git_repo / ".codoc-engine.yml").is_file()
        assert result.vale_ini is not None
        vale = (git_repo / result.vale_ini).read_text(encoding="utf-8")
        assert "Vocab = Codoc" in vale
        assert "StylesPath = styles" in vale
        accept = (git_repo / result.vocab_accept).read_text(encoding="utf-8")
        assert accept == "Codoc\nZensical\n"
        assert (
            git_repo
            / ".codoc"
            / "generated"
            / "styles"
            / "config"
            / "vocabularies"
            / "Codoc"
            / "reject.txt"
        ).is_file()

    def test_vale_disabled_skips_vale_files(self, git_repo: Path) -> None:
        (git_repo / "codoc.yaml").write_text(
            "vale:\n  enabled: false\n",
            encoding="utf-8",
        )
        config = load_project_config(git_repo / "codoc.yaml")
        assert not config.vale.enabled
        result = write_generated(git_repo, config)
        assert result.vale_ini is None
        assert (git_repo / result.engine).is_file()
        assert not (git_repo / ".codoc" / "generated" / ".vale.ini").exists()

    def test_unsupported_engine(self, git_repo: Path) -> None:
        (git_repo / "codoc.yaml").write_text(
            "engine:\n  name: hugo\n",
            encoding="utf-8",
        )
        with pytest.raises(CodegenError) as caught:
            ensure_generated(git_repo)
        assert "unsupported engine" in str(caught.value)

    def test_missing_codoc_yaml(self, git_repo: Path) -> None:
        with pytest.raises(CodegenError):
            ensure_generated(git_repo)
